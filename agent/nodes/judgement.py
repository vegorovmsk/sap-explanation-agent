# -*- coding: utf-8 -*-
"""
Что делать, когда модель-судья не смогла ответить по схеме.

Прогон 14.09 потерял два кейса из девятнадцати не из-за плохого разбора, а
из-за одного неразобранного JSON: модель упёрлась в потолок токенов, починка не
помогла, узел бросил `StructuredOutputError` — и весь прогон умер со статусом
`error`, выбросив уже собранные факты, уже прочитанные источники и уже готовый
черновик ответа. Это несоразмерно: сломалось СУЖДЕНИЕ, а работа цела.

Правило, по которому здесь всё устроено: сбой суждения деградирует до самого
осторожного исхода, а не отменяет прогон.

  · не удалось оценить полноту   → считаем, что фактов не хватает;
  · не удалось сверить источники → `insufficient`, вердикта нет;
  · не удалось проверить ответ   → ответ остаётся, но с оговоркой, что проверка
                                   не состоялась.

Осторожный исход — всегда тот, который НЕ выдаёт непроверенное за проверенное.
Обратное («не смогли проверить, значит всё в порядке») превратило бы аварию в
молчаливое одобрение, а это худшее, что может сделать агент-объяснитель.

Сбой при этом никогда не замалчивается: он попадает в трассу отдельным событием
и доходит до пользователя текстом. Деградация — это про то, чтобы не потерять
работу, а не про то, чтобы скрыть поломку.
"""
from __future__ import annotations

from llm.client import LLMError


def degrade(trace, node: str, exc: Exception, what: str) -> None:
    """Записать несостоявшееся суждение в трассу."""
    trace.event("judgement.degraded", node=node, status="degraded",
                error=f"{type(exc).__name__}: {str(exc)[:200]}", fallback=what)
    trace.decision(node=node, action="judgement_failed",
                   reason_summary=f"суждение не состоялось, принят осторожный "
                                  f"исход: {what}")


def is_judgement_failure(exc: Exception) -> bool:
    """Сбой модели-судьи, а не ошибка в коде агента.

    Ловим только ошибки провайдера и разбора: `TypeError` в собственном узле
    деградировать нельзя — его надо чинить, и падение прогона здесь правильный
    исход.
    """
    return isinstance(exc, LLMError)
