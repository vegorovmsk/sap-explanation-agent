"""Промпт узла act: модель сама выбирает, какой инструмент вызвать следующим."""
from __future__ import annotations

from agent.prompts.common import ROLE, evidence_digest, question_block, sources_block
from agent.state import AgentState

SYSTEM = ROLE + """

Сейчас твоя задача — СОБРАТЬ ФАКТЫ, а не ответить. Вызывай инструменты.

Как выбирать:
- по конкретному заказу начинай с read_task и read_plan: сначала что просили,
  потом что система сделала;
- любой норматив — только через lookup_nsi, по памяти числа не приводи;
- нормативное подтверждение ищи через search_regulations; если известен номер
  таблицы НСИ, передай его параметром table — так пункт находится точно;
- смысл кода «Причина» и замечаний НСИ выводится из кода валидации: реестра
  кодов в системе нет, поэтому нужен search_code;
- не знаешь, в какой таблице НСИ искать или как называются её колонки — сначала
  вызови list_nsi_tables: он вернёт номера таблиц, названия и состав колонок.
  Таблицы разные для разных этапов: допустимость печатных линий и допустимость
  линий экструзии лежат в разных таблицах;
- сверяя норму с реализацией, вызывай search_code с параметром clause — это
  переход по графу связей, он точнее свободного запроса.

За один ход вызывай столько инструментов, сколько нужно для следующего шага, но
не повторяй уже сделанные вызовы: их результаты перед тобой. Если фактов
достаточно, не вызывай ничего и коротко напиши, что собрано.

Плана сбора в тексте не пиши. Перечисление «сначала проверим то, потом это» —
это не сбор, а его обещание: агент от такого хода не получает ни одного факта.
Пока фактов нет, единственный осмысленный ход — вызов инструмента.

Если предыдущий вызов не удался, ниже будет его текст ошибки и подсказка.
Не повторяй тот же вызов наугад: сначала исправь то, на что указывает ошибка —
неверный номер таблицы, несуществующая колонка, нехватка обязательного аргумента."""


def _stage_map(state: AgentState) -> str:
    """Карта источников этапа. Номера таблиц и координаты — не для угадывания."""
    smap = state.stage_map or {}
    if not smap:
        return ""
    lines = [f"\n\nКАРТА ИСТОЧНИКОВ ЭТАПА «{smap['этап']}» "
             f"(собрана по индексам стенда, а не предположена):"]
    for t in smap.get("таблицы", [])[:10]:
        norms = ", ".join(t["пункты"][:4]) or "нормы не ссылаются"
        code = ", ".join(t["функции"][:2]) or "код этапа не читает"
        lines.append(f"- табл. {t['таблица']}: нормы {norms}; код {code}")
    if smap.get("нормы_без_кода"):
        lines.append("- норма ссылается, а код этапа не читает: табл. "
                     + ", ".join(smap["нормы_без_кода"]))
    if smap.get("код_без_норм"):
        lines.append("- код этапа читает, а нормы не ссылаются: табл. "
                     + ", ".join(smap["код_без_норм"]))
    for c in smap.get("непокрытые_условия", []):
        lines.append(f"- ПРОВЕРЬ: норма {c['пункт']} называет параметр "
                     f"«{c['параметр']}», в коде этапа "
                     f"({', '.join(c['код_этапа'])}) он не встречается. "
                     f"Прочитай и норму, и функцию отбора — это кандидат "
                     f"в расхождение, а не вывод.")
    lines.append("Номера таблиц и координаты функций берите отсюда: здесь они точные.")
    return "\n".join(lines)


def _failures(state: AgentState) -> str:
    if not state.failed_calls:
        return ""
    lines = []
    for f in state.failed_calls[-4:]:
        args = ", ".join(f"{k}={v}" for k, v in (f.get("аргументы") or {}).items()
                         if k != "client")
        lines.append(f"- {f['инструмент']}({args})\n  ошибка: {f.get('ошибка')}"
                     + (f"\n  подсказка: {f['подсказка']}" if f.get("подсказка") else ""))
    return "\n\nНеудачные вызовы — исправь причину, а не повторяй:\n" + "\n".join(lines)


def _repeats(state: AgentState) -> dict[str, int]:
    """Сколько раз каждый пробел уже заявлялся. Сравнение грубое — по началу фразы."""
    counts: dict[str, int] = {}
    for g in state.gap_history:
        key = " ".join(str(g).lower().split())[:60]
        counts[key] = counts.get(key, 0) + 1
    return counts


def _gaps_block(state: AgentState) -> str:
    if not state.gaps:
        return ""
    counts = _repeats(state)
    lines, stuck = [], False
    for g in state.gaps:
        n = counts.get(" ".join(str(g).lower().split())[:60], 0)
        lines.append(f"- {g}" + (f"  ← заявлен уже {n}-й раз" if n >= 2 else ""))
        stuck = stuck or n >= 2
    out = "\nЧто не удалось найти на прошлых шагах:\n" + "\n".join(lines)
    if stuck:
        out += ("\n\nПовторно заявленный пробел закрывается не формулировкой, а вызовом. "
                "Сделай конкретный вызов, который его закрывает: номер таблицы НСИ есть "
                "в поле «таблицы_НСИ» у уже найденных фрагментов кода, состав колонок — "
                "в list_nsi_tables, пункт нормы — в search_regulations с параметром table. "
                "Если закрыть нечем, не повторяй пробел: ничего не вызывай и напиши, "
                "каких данных в системе нет.")
    return out


def build_messages(state: AgentState, iteration: int, catalogue: str = "") -> list[dict]:
    gaps = _gaps_block(state)
    tables = (f"\n\nТаблицы НСИ стенда (номер, назначение и состав колонок):\n"
              f"{catalogue}\n"
              f"Фильтруй и запрашивай колонки ТОЛЬКО по именам из этого списка — "
              f"они приведены дословно. Колонки с другим именем в таблице нет, и "
              f"вызов с ней не состоится."
              if catalogue else "")
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content":
            f"{question_block(state)}\n\n{sources_block(state)}\n\n"
            f"Итерация сбора фактов: {iteration}{tables}"
            f"{_stage_map(state)}\n\n"
            f"Уже собранные факты:\n{evidence_digest(state.evidence)}{gaps}"
            f"{_failures(state)}"},
    ]
