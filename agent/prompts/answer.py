# -*- coding: utf-8 -*-
"""Промпт узла answer и шаблон финального ответа пользователю."""
from __future__ import annotations

from agent.prompts.common import ROLE, evidence_digest, question_block
from agent.state import AgentState

SYSTEM = ROLE + """

Теперь напиши ответ пользователю — инженеру-планировщику, который знает
производство, но не знает внутренностей системы.

Требования к ответу:
- краткий вывод в одну-две фразы: что произошло и почему;
- объяснение цепочкой: что было в задании, что говорит НСИ, что предписывает
  регламент, что сделала система. Каждое звено — с координатой источника
  в квадратных скобках прямо в тексте;
- в квадратные скобки попадают ТОЛЬКО координаты из списка разрешённых, дословно
  и по одной: две соседние строки таблицы — это две координаты, а не одна
  «строки 3 и 7». Координаты, которой нет в списке, не существует;
- если в списке нет ни одной ссылки на регламент, значит норма не проверялась.
  Тогда регламент в ответе не упоминается вообще — ни номером, ни пунктом,
  ни словами «согласно регламенту». Звено цепочки просто отсутствует, и это
  нормально: лучше короткое объяснение, чем красивое с выдуманной ссылкой;
- таблицу НСИ называй так, как она записана в координате прочитанного факта,
  а не именем файла;
- не усиливай факты. Перечень допустимых значений не превращается в
  утверждение, что допустимо ровно одно из них; «строка не найдена» не превращается в «строки
  нет»; «ключ записан другим символом» не превращается в «норматив отсутствует».
  Слова «только», «единственный», «всегда», «никогда» пиши лишь тогда, когда
  ровно это написано в факте;
- никаких предложений изменить код, алгоритм, НСИ или регламент;
- по-русски, без англицизмов вроде «фича» и «кейс», спокойным рабочим тоном."""

SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["summary", "explanation", "cited_locators", "confidence"],
    "properties": {
        "summary": {"type": "string", "description": "Краткий вывод, одна-две фразы"},
        "explanation": {"type": "string",
                        "description": "Объяснение цепочкой, с координатами в тексте"},
        "cited_locators": {"type": "array", "items": {"type": "string"},
                           "description": "Все координаты, на которые опирается ответ"},
        "confidence": {"type": "string", "enum": ["низкая", "средняя", "высокая"]},
    },
}

STATUS_LINE = {
    "conflict": "противоречит документации — подготовлено обращение в поддержку",
    "insufficient": "не может быть объяснено по доступным данным",
}

# Чему именно соответствует решение — зависит от того, что успели прочитать.
# Раньше в шаблоне стояло глухое «соответствует данным НСИ и регламенту», и при
# непрочитанном регламенте ответ утверждал соответствие норме без единого факта
# о норме. Живой прогон это и поймал: модель-рецензент забраковала собственную
# служебную строку агента.
VERDICT_SOURCES = {
    "task": "заданию",
    "nsi": "данным НСИ",
    "regulations": "регламенту",
    "code": "реализации расчёта",
    "plan": "результату расчёта",
    "logs": "журналу расчёта",
}


def about_decision(state: AgentState) -> bool:
    """Идёт ли речь о конкретном решении системы, а не об её устройстве.

    Решение есть там, где есть заказ: его куда-то поставили, отложили или сняли.
    Вопрос «какие этапы планирования есть в системе» решения не содержит — там
    нечего одобрять или оспаривать. Живой прогон показал, во что превращается
    смешение: на такой вопрос агент отвечал «Вывод: решение системы соответствует
    регламенту и реализации расчёта», хотя никакого решения не разбирал.
    """
    return bool(state.entities.get("order_number")) or "plan" in state.sources_seen


def verdict_line(state: AgentState) -> str:
    """Итоговая строка целиком, вместе с подлежащим.

    Подлежащее зависит от вопроса: у разбора решения это «решение системы», у
    вопроса об устройстве — сама реализация. Собирать строку из общего начала и
    переменного конца нельзя: начало здесь и есть то, что меняется.
    """
    decision = about_decision(state)
    subject = "решение системы" if decision else "реализация"

    if state.status == "conflict":
        return ("решение системы противоречит документации — подготовлено обращение "
                "в поддержку" if decision else
                "реализация расходится с документацией — подготовлено обращение "
                "в поддержку")
    if state.status != "confirmed":
        tail = STATUS_LINE.get(state.status, state.status)
        return (f"{subject} {tail}" if decision
                else "объяснить по доступным данным не удалось")

    named = [VERDICT_SOURCES[s] for s in VERDICT_SOURCES if s in state.sources_seen
             and s not in ("plan", "task")]
    if not decision:
        # Ответ про устройство ничего не одобряет: он говорит, по каким
        # источникам собрано описание.
        where = ", ".join(named) if named else "собранным фактам"
        return f"описание собрано по источникам: {where}"
    if not named:
        return f"{subject} подтверждается собранными фактами"
    if len(named) == 1:
        return f"{subject} соответствует {named[0]}"
    return f"{subject} соответствует " + ", ".join(named[:-1]) + f" и {named[-1]}"


def allowed_block(state: AgentState) -> str:
    """Явный список координат, которые разрешено процитировать.

    Раньше в системном промпте стоял пример координаты «[ТР-ПЕЧ-2026/02 п. 3.1]»,
    и живые прогоны дважды показали ровно эту ссылку в ответе — при том, что
    регламент в тех прогонах не открывали. Пример из промпта модель приняла за
    факт. Поэтому примеров координат в промпте больше нет, а разрешённый список
    печатается прямо в задании.
    """
    known = sorted(state.locators())
    if not known:
        return "РАЗРЕШЁННЫЕ КООРДИНАТЫ: нет ни одной. Ссылаться не на что."
    lines = "\n".join(f"- {k}" for k in known)
    return ("РАЗРЕШЁННЫЕ КООРДИНАТЫ (других не существует, переписывай дословно):\n"
            + lines)


def build_messages(state: AgentState) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content":
            f"{question_block(state)}\n\nСобранные факты:\n{evidence_digest(state.evidence)}"
            f"\n\n{allowed_block(state)}"},
    ]


def build_revision_messages(state: AgentState, claims: list[str]) -> list[dict]:
    """Переписывание ответа по ключевым замечаниям проверки.

    Проверка нашла утверждения, не опирающиеся на факты. Забраковать из-за них
    весь разбор — потеря: вывод, как правило, верен, лишняя фраза — нет.
    Поэтому ответ собирается заново, но без спорных утверждений.
    """
    bad = "\n".join(f"- {c}" for c in claims[:5])
    return build_messages(state) + [
        {"role": "assistant", "content": (state.answer_explanation or "")[:3000]},
        {"role": "user", "content":
            "Проверка ответа нашла утверждения, которые не опираются ни на один "
            f"факт:\n{bad}\n\n"
            "Собери ответ заново без них: убери сами утверждения и всё, что на "
            "них держалось. Вывод, который подтверждается фактами, оставь как был "
            "и не усиливай его. Если после удаления объяснение стало короче — так "
            "и должно быть.\n"
            "Но факты с координатами не выбрасывай: числа, даты и значения, "
            "прочитанные из источников, должны остаться в объяснении вместе со "
            "ссылками. Убирают спорное утверждение, а не основания."},
    ]


def build_repair_messages(state: AgentState, invented: list[str], draft: str) -> list[dict]:
    """Одна прямая просьба переписать ответ без неподтверждённых ссылок."""
    bad = "\n".join(f"- {i}" for i in invented[:5])
    return build_messages(state) + [
        {"role": "assistant", "content": draft[:3000]},
        {"role": "user", "content":
            "В ответе есть координаты, которых нет в разрешённом списке:\n"
            f"{bad}\n\n"
            "Значит, этих источников агент не читал. Перепиши ответ так, чтобы "
            "их не было ни в тексте, ни в cited_locators, и чтобы утверждения, "
            "которые на них опирались, тоже исчезли. Остальное не меняй."},
    ]


def render(state: AgentState) -> str:
    """Собирает финальный текст по фиксированному шаблону.

    Шаблон нужен не для красоты: он делает ответ проверяемым. Проверенные
    источники, статус и признак эскалации стоят на одних и тех же местах, поэтому
    их можно сверять автоматически — этим занимается прогон evals.
    """
    parts = [f"Краткий вывод:\n{state.answer_summary}", ""]
    parts.append("Проверенные источники:")
    # Факт без координаты в перечень источников не идёт. Не косметика: раньше
    # строка склеивалась через ", ".join и падала на первом же None, унося весь
    # прогон в TypeError уже после того, как ответ был написан. А по смыслу
    # координата здесь и есть содержание раздела: строка «Проверенные источники»
    # существует затем, чтобы читатель мог открыть каждую и убедиться сам.
    seen: dict[str, list[str]] = {}
    for e in state.evidence:
        if not e.locator:
            continue
        seen.setdefault(e.source, [])
        if e.locator not in seen[e.source]:
            seen[e.source].append(e.locator)
    from agent.prompts.common import SOURCE_NAMES
    for source, locators in seen.items():
        shown = ", ".join(locators[:4])
        more = f" и ещё {len(locators) - 4}" if len(locators) > 4 else ""
        parts.append(f"- {SOURCE_NAMES.get(source, source)}: {shown}{more}")
    if not seen:
        parts.append("- нет")
    parts += ["", "Объяснение:", state.answer_explanation, ""]
    parts.append(f"Вывод: {verdict_line(state)}.")
    parts.append(f"Уверенность: {state.confidence_label}")
    parts.append("Нужно обращение в поддержку: " + ("да" if state.ticket else "нет"))
    if state.gaps:
        parts += ["", "Чего не удалось подтвердить:"] + [f"- {g}" for g in state.gaps]
    return "\n".join(parts)
