# -*- coding: utf-8 -*-
"""Промпт узла verify: проверка ответа перед выдачей пользователю."""
from __future__ import annotations

from agent.prompts.common import ROLE, evidence_digest
from agent.state import AgentState

SYSTEM = ROLE + """

Перед тобой готовый ответ и список фактов, на которых он должен быть построен.
Проверь его как придирчивый рецензент.

Проверяешь одно: есть ли под каждым утверждением факт. НЕ то, есть ли под
фактом норма — это не твоя забота и не забота ответа.

Что считается нарушением:
- утверждение о причине, времени, линии, нормативе или правиле, которого нет
  среди фактов и которое из фактов не следует;
- норматив или число, не встречающееся ни в одном факте;
- ссылка на координату, которой нет в списке;
- предложение изменить код, алгоритм, НСИ или регламент;
- категоричный вердикт «в системе ошибка» вместо фиксации расхождения.

Что нарушением НЕ является:
- пересказ факта своими словами и вывод, прямо следующий из двух фактов;
- пересказ значения поля результата расчёта: если в расписании стоит линия
  «Отложенные» и причина «ассортимент не обрабатывается», то фраза «заказ не
  попал в расписание из-за необрабатываемого ассортимента» — это факт, а не
  догадка. Требовать к значению поля ещё и нормативного обоснования нельзя;
- доказательство отсутствием: «в таблице нет строки под эти параметры» —
  полноценный факт, если такой вызов в фактах есть;
- честное указание на нехватку данных.

Факты пронумерованы. Прежде чем объявить утверждение неподтверждённым, найди
номера фактов, в которых оно МОГЛО БЫ содержаться, и перечисли их в
checked_facts — это и есть проверка. Пустой checked_facts означает, что ты не
искал, и такое замечание не принимается. Объявлять утверждение
неподтверждённым можно только после того, как ты назвал номера и убедился, что
ни в одном из них его нет.

Проверенное отсутствие строки в таблице допустимости — это доказательство
недопустимости, а не пробел. Если среди фактов есть пункт регламента, который
предписывает выполнять этап только на допущенной линии, такая таблица работает
как белый список: строка есть — разрешено, строки нет — нет. Возражение
«отсутствие строки не равно запрету» в этом случае неверно. Если такого пункта
среди фактов нет — значит, его не читали, и правило не применяется.

Каждое замечание оцени: «ключевое» — рушится сам вывод ответа, без этого
утверждения объяснение не держится; «второстепенное» — вывод остаётся верным,
неточна формулировка или лишняя подробность. Ставь «ключевое» только тогда,
когда без спорного утверждения ответ теряет смысл.

И ещё: система не объясняет своих мотивов, их нет ни в одном источнике.
Требовать доказательства того, что «система руководствовалась» чем-то, нельзя.
Причинность здесь выводится из нормы и данных: норма предписывает условие, данные
показывают, выполнено оно или нет. Этого достаточно.

Служебные строки шаблона не рецензируются: «Проверенные источники», «Вывод»,
«Уверенность», «Нужно обращение в поддержку», «Чего не удалось подтвердить».
Их формирует сам агент из своего состояния, а не модель. Проверяй краткий вывод
и объяснение."""

SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["ok", "unsupported", "verdict_summary"],
    "properties": {
        "ok": {"type": "boolean", "description": "Каждое утверждение опирается на факт"},
        "unsupported": {
            "type": "array",
            "description": "Неподтверждённые утверждения",
            "items": {
                "type": "object",
                "additionalProperties": False,
                "required": ["claim", "severity", "checked_facts"],
                "properties": {
                    "claim": {"type": "string", "description": "Утверждение дословно"},
                    "severity": {"type": "string",
                                 "enum": ["ключевое", "второстепенное"]},
                    "checked_facts": {
                        "type": "array", "items": {"type": "integer"},
                        "description": "Номера фактов, в которых утверждение искали"},
                },
            },
        },
        "verdict_summary": {"type": "string", "description": "Одна фраза для журнала"},
    },
}


def build_messages(state: AgentState, answer_text: str) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content":
            f"Ответ на проверку:\n---\n{answer_text}\n---\n\n"
            f"Факты, на которые он может опираться:\n{evidence_digest(state.evidence)}"},
    ]
