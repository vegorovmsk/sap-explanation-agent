# -*- coding: utf-8 -*-
"""Промпт узла check_consistency: сходятся ли источники между собой."""
from __future__ import annotations

from agent.prompts.common import ROLE, evidence_digest, question_block
from agent.state import AgentState

SYSTEM = ROLE + """

Сейчас ты СВЕРЯЕШЬ ИСТОЧНИКИ между собой. Ответ пользователю писать не нужно.

Цепочка, которую надо проверить: задание → НСИ → регламент → код → результат
расчёта. Проверяется она настолько, насколько её затрагивает вопрос. Вопрос без
номера заказа — про устройство системы, а не про судьбу партии: для него цепочка
короче, регламент ↔ НСИ ↔ код, и отсутствие задания или расписания среди фактов
пробелом не является. Требовать задание там, где о заказе не спрашивали, нельзя.

ВОПРОС ПОЛЬЗОВАТЕЛЯ ИСТОЧНИКОМ НЕ ЯВЛЯЕТСЯ. «Почему не на такой-то линии» —
это не утверждение, что заказ должен быть на ней. Несовпадение ожиданий пользователя с
решением системы — не конфликт, а как раз то, что предстоит объяснить.
Конфликт бывает только между двумя ПРОЧИТАННЫМИ источниками, и у каждой стороны
обязана быть координата из списка фактов.

Возможные исходы:

confirmed   — источники согласуются, решение системы объяснимо и подтверждено.
              Сюда же относится случай «система поступила не так, как ожидал
              пользователь, и НСИ объясняет почему»: это подтверждение, а не спор;
conflict    — источники противоречат друг другу: норматив есть, а поведение иное;
              регламент требует одного, код делает другое; НСИ и план расходятся.
              Это НЕ повод объявить ошибку — это повод готовить обращение в поддержку;
insufficient — доказательств не хватает, чтобы утверждать что-либо определённое.

Сверяя норму с кодом, сверяй УСЛОВИЯ, а не темы. Совпадение по теме не равно
совпадению по условию: если норма называет два параметра, а в прочитанном коде
читается только один, это расхождение, а не подтверждение. Похожая по смыслу
таблица не заменяет условие — норматив выработки и диапазон калибров не то же
самое, что диаметр кольца. И наоборот: нельзя объявить условие выполненным на
том основании, что код вообще обращается к какой-то таблице НСИ.

Проверенное отсутствие строки в таблице допустимости — это доказательство
недопустимости, а не пробел. Если среди фактов есть пункт регламента, который
предписывает выполнять этап только на допущенной линии, такая таблица работает
как белый список: строка есть — разрешено, строки нет — нет. Возражение
«отсутствие строки не равно запрету» в этом случае неверно. Если такого пункта
среди фактов нет — значит, его не читали, и правило не применяется.

Отличай противоречие от отсутствия данных. Если норматива просто нет в таблице,
а регламент запрещает запуск без норматива — это согласие источников, а не
конфликт. Если ключ в таблице записан другим алфавитом — это дефект данных и
конфликт между заданием и НСИ.

Не прочитанный регламент — это нехватка нормативного подтверждения, а не
противоречие. Если план и НСИ сходятся, а до регламента дело не дошло, это
confirmed с умеренной уверенностью, а не conflict.

Уверенность ставь честно: 0.9 — цепочка подтверждена всеми звеньями,
0.5 — есть пробел, 0.2 — почти ничего не подтверждено.

Ответ — ТОЛЬКО JSON-объект по схеме. Рассуждений вне полей схемы быть не должно,
reason_summary — одна-две фразы."""

SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "required": ["status", "confidence", "conflicts", "reason_summary"],
    "properties": {
        "status": {"type": "string", "enum": ["confirmed", "conflict", "insufficient"]},
        "confidence": {"type": "number", "description": "От 0 до 1"},
        "conflicts": {
            "type": "array",
            "items": {
                "type": "object",
                "additionalProperties": False,
                "required": ["subject", "expected", "expected_source", "actual",
                             "actual_source", "severity"],
                "properties": {
                    "subject": {"type": "string", "description": "В чём расхождение"},
                    "expected": {"type": "string", "description": "Что предписано"},
                    "expected_source": {"type": "string", "description": "Координата источника нормы"},
                    "actual": {"type": "string", "description": "Что на самом деле"},
                    "actual_source": {"type": "string", "description": "Координата источника факта"},
                    "severity": {"type": "string", "enum": ["low", "medium", "high"]},
                },
            },
        },
        "reason_summary": {"type": "string",
                           "description": "Одна-две фразы для журнала, до 300 символов"},
    },
}


def candidates_block(state: AgentState) -> str:
    """Кандидаты в расхождения, найденные обходом индексов.

    Это лексическая находка кода, а не доказательство: параметр назван в норме
    и не встречается в коде этапа. Подтверждать или снимать её надо по
    прочитанным фактам, и только по ним.
    """
    items = (state.stage_map or {}).get("непокрытые_условия") or []
    if not items:
        return ""
    lines = [f"- норма {c['пункт']} называет «{c['параметр']}», "
             f"в коде этапа он не встречается" for c in items[:4]]
    return ("\n\nВЕРСИИ, найденные обходом индексов (проверить по фактам, "
            "не принимать на веру):\n" + "\n".join(lines)
            + "\nЕсли среди фактов есть и норма, и функция отбора, и параметра "
              "в функции действительно нет — это расхождение с координатами. "
              "Если норма или код не прочитаны, версия остаётся непроверенной, "
              "и это нехватка доказательств, а не конфликт.")


def build_messages(state: AgentState) -> list[dict]:
    return [
        {"role": "system", "content": SYSTEM},
        {"role": "user", "content":
            f"{question_block(state)}\n\nСобранные факты:\n"
            f"{evidence_digest(state.evidence)}{candidates_block(state)}"},
    ]
