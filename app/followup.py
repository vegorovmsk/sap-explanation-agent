# -*- coding: utf-8 -*-
"""
Замыкание уточняющего вопроса: ответ пользователя склеивается с исходным.

Зачем это нужно. Ветка `clarify` задаёт ровно один вопрос — «Укажите номер
заказа» — и на этом прогон заканчивается. Пользователь отвечает «Z-1060», и
начинается НОВЫЙ прогон, который видит только эту строку и понятия не имеет, о
чём спрашивал минуту назад. Уточнение задавалось, но не замыкалось: чтобы
получить ответ, приходилось повторять вопрос целиком. В терминальном узле при
этом написано «иначе пользователь получает анкету вместо диалога» — а диалога-то
и не было.

Чего здесь СОЗНАТЕЛЬНО нет — переноса фактов между ходами. Склеивается только
формулировка вопроса; источники следующий прогон читает заново, с нуля. Иначе
рухнула бы главная гарантия агента: каждое утверждение в ответе снабжено
координатой того, что прочитано В ЭТОМ прогоне. Унаследованный факт такой
координаты не имеет — он взят из чужой доказательной базы, которую механические
проверки этого прогона не видели. Память о разговоре вправе помнить, ЧТО
спрашивали; помнить, что при этом выяснилось, она не вправе.

Склеенный вопрос проходит входной шлюз как обычный: ответ пользователя — это
пользовательский ввод, и проверки на инъекции к нему применяются в полном объёме.
"""
from __future__ import annotations

# Больше одного круга уточнений не даём. Два подряд означают, что вопрос не
# складывается в принципе, и третий заход превратит диалог в ту самую анкету.
MAX_ROUNDS = 1


def merge(question: str, reply: str) -> str:
    """Исходный вопрос плюс ответ на уточнение — одной формулировкой."""
    question = " ".join((question or "").split())
    reply = " ".join((reply or "").split())
    if not reply:
        return question
    if not question:
        return reply
    return f"{question} Уточнение: {reply}"


def pending(result: dict | None) -> str | None:
    """Вопрос, ждущий ответа, если прошлый прогон закончился уточнением."""
    if not result or result.get("status") != "clarify":
        return None
    return result.get("question") or None
